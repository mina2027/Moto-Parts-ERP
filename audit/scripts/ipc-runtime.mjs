import { createRequire } from 'node:module';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '../..');
const desktop = path.join(root, 'pos-desktop');
const require = createRequire(path.join(desktop, 'package.json'));
const target = path.join(root, process.env.POS_AUDIT_EVIDENCE || 'audit/evidence/pass3', 'ipc-runtime');
fs.mkdirSync(target, { recursive: true });
const originalPreload = path.join(target, 'original.cjs');
await require('esbuild').build({ entryPoints: [path.join(root, 'audit/originals-pass3/pos-desktop/src/preload/index.ts')], bundle: true, platform: 'node', format: 'cjs', external: ['electron'], outfile: originalPreload, plugins: [{ name: 'original-contract', setup(build) { build.onResolve({ filter: /shared\/ipc$/ }, () => ({ path: path.join(desktop, 'src/shared/ipc.ts') })); } }] });
const entry = `
const { app, BrowserWindow, ipcMain } = require('electron');
const assert = require('node:assert/strict'); const fs = require('node:fs'); const path = require('node:path'); const { pathToFileURL } = require('node:url');
const { createIpcBoundary, secureNavigation, assertSender } = require('./src/main/ipcSecurity.ts');
const { validateIpcArgs } = require('./src/main/ipcValidation.ts');
const { invokeData } = require('./src/main/dataAccess.ts');
const { projectSession, projectDisplaySettings, projectDisplayState } = require('./src/main/displayProjection.ts');
const { DEFAULT_SETTINGS } = require('@moto/shared'); const { IPC } = require('./src/shared/ipc.ts');
const target = ${JSON.stringify(target)}; const originalPreload = ${JSON.stringify(originalPreload)}; const desktop = ${JSON.stringify(desktop)};
app.setPath('userData', path.join(target,'isolated-profile'));
app.whenReady().then(async () => {
  let failed=false; const windows=[]; const checks=[];
  const make=(preload,additionalArguments=[])=>{const w=new BrowserWindow({show:false,webPreferences:{preload,additionalArguments,sandbox:true,contextIsolation:true,nodeIntegration:false}});w.webContents.on("console-message", (_e,level,message)=>console.log("renderer",message));windows.push(w);return w;};
  const page=path.join(target,'index.html'), displayPage=path.join(target,'display.html');
  fs.writeFileSync(page,'<!doctype html><div>SYNTHETIC</div>'); fs.writeFileSync(displayPage,'<!doctype html><div>SYNTHETIC DISPLAY</div>');
  const url=pathToFileURL(page).href, displayUrl=pathToFileURL(displayPage).href;
  const synthetic={user:{id:'audit',branchId:'br-1'},permissions:['sales.create'],token:'SYNTHETIC_PRIVATE_TOKEN',refreshToken:'SYNTHETIC_REFRESH',expiresAt:''};
  try {
    // Reproduce the old sender-blind handler with the exact preserved original preload.
    ipcMain.handle(IPC.authCached,()=>synthetic);
    const before=make(originalPreload); await before.loadFile(displayPage);
    assert.equal(await before.webContents.executeJavaScript('window.pos.auth.cachedSession().then(s=>s.token)'),synthetic.token);
    checks.push('before: foreign customer-display document obtains full cached token through original preload');
    ipcMain.removeHandler(IPC.authCached);
    let current=synthetic;
    const main=make(path.join(desktop,'out/preload/index.cjs'));
    const boundary=createIpcBoundary(ipcMain,()=>main.webContents,url,()=>current,validateIpcArgs);
    boundary.handle(IPC.authCached,()=>projectSession(current));
    boundary.handle(IPC.authLogin,()=>projectSession(current=synthetic));
    boundary.handle(IPC.authLogout,()=>{current=null;});
    boundary.handle(IPC.appVersion,()=>app.getVersion());
    boundary.handle(IPC.appUnpair,()=>{throw Error('MUST_NOT_REACH');});
    boundary.handle(IPC.data,(_e,method,arg)=>invokeData({customers:()=>[],createSale:()=>{throw Error('MUST_NOT_WRITE');}},current,'br-1',method,arg));
    secureNavigation(main.webContents,url); await main.loadFile(page);
    const cached=await main.webContents.executeJavaScript('window.pos.auth.cachedSession()'); assert.equal(cached.token,undefined); assert.equal(cached.refreshToken,undefined);
    checks.push('after: legitimate main top-frame session is available without tokens');
    assert.match(await main.webContents.executeJavaScript('window.pos.app.unpair().catch(e=>e.message)'),/PERMISSION_DENIED/);
    assert.match(await main.webContents.executeJavaScript('window.pos.data.createSale({branchId:"br-1",type:"cash",items:[{productId:"p",name:{ar:"synthetic"},quantity:-1,unitPrice:10}],payments:[]}).catch(e=>e.message)'),/INVALID_IPC_ARGUMENT/);
    checks.push('after: actual cashier unpair and negative sale IPC denied');
    const forged=make(path.join(desktop,'out/preload/index.cjs')); await forged.loadFile(displayPage);
    assert.match(await forged.webContents.executeJavaScript('window.pos.auth.cachedSession().catch(e=>e.message)'),/IPC_SENDER_DENIED/);
    checks.push('after: a separate window with full preload cannot invoke main handlers');
    const display=make(path.join(desktop,'out/preload/index.cjs'),['--pos-customer-display']);
    ipcMain.handle(IPC.displaySettings,(event)=>{assertSender(event,display.webContents,displayUrl);return projectDisplaySettings(DEFAULT_SETTINGS);});
    secureNavigation(display.webContents,displayUrl); await display.loadFile(displayPage);
    assert.equal(await display.webContents.executeJavaScript('typeof window.pos'),'undefined');
    assert.deepEqual(Object.keys(await display.webContents.executeJavaScript('window.posDisplay.settings()')).sort(),['company','currency','invoice']);
    const statePromise=display.webContents.executeJavaScript('new Promise(resolve=>window.posDisplay.onState(resolve))');
    await new Promise(r=>setTimeout(r,100));
    display.webContents.send(IPC.evDisplayState,projectDisplayState({lines:[{productId:'p',name:{ar:'synthetic'},unitPrice:10,quantity:1,discountPercent:0,unitCost:8}],customer:{name:{ar:'customer'},balance:1000},invoiceDiscount:0,lastSaleId:null}));
    const state=await statePromise; assert.equal(state.lines[0].unitCost,undefined); assert.equal(state.customer.balance,undefined);
    checks.push('after: customer-display preload has only read-only settings/state and redacted payloads');
    const iframeBridge=await main.webContents.executeJavaScript('new Promise(resolve=>{const f=document.createElement("iframe");f.src='+JSON.stringify(url)+';document.body.appendChild(f);setTimeout(()=>resolve(typeof f.contentWindow.pos),300);})');
    assert.equal(iframeBridge,'undefined');
    checks.push('after: iframe navigation denied and no privileged child-frame bridge');
    await main.webContents.executeJavaScript('location.href='+JSON.stringify(displayUrl)); await new Promise(r=>setTimeout(r,200)); assert.equal(main.webContents.getURL(),url);
    await main.webContents.executeJavaScript('window.pos.auth.logout()');
    assert.match(await main.webContents.executeJavaScript('window.pos.data.customers().catch(e=>e.message)'),/AUTH_REQUIRED/);
    checks.push('after: foreign navigation blocked; logout denies actual data IPC');
    fs.writeFileSync(path.join(target,'results.json'),JSON.stringify({passed:true,electron:process.versions.electron,checks},null,2));console.log(JSON.stringify({passed:true,checks:checks.length}));
  } catch(error) { console.error(error); fs.writeFileSync(path.join(target,'results.json'),JSON.stringify({passed:false,error:String(error),checks},null,2));failed=true; }
  finally { for(const w of windows) if(!w.isDestroyed())w.destroy();app.exit(failed?1:0); }
});
`;
const outfile=path.join(target,'probe.cjs');
await require('esbuild').build({stdin:{contents:entry,resolveDir:desktop},bundle:true,platform:'node',format:'cjs',external:['electron'],outfile});
const env={...process.env}; delete env.ELECTRON_RUN_AS_NODE;
const result=spawnSync(require('electron'),[outfile],{cwd:desktop,env,windowsHide:true,stdio:'inherit',timeout:60000});
if(result.error)console.error(result.error); const evidence=JSON.parse(fs.readFileSync(path.join(target,'results.json'),'utf8')); process.exit(result.status===0 && evidence.passed?0:1);
